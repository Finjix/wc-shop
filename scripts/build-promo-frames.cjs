// Encode both static frame sheets near the original GIF byte budgets.
const fs = require('node:fs');
const path = require('node:path');
const sharp = require('../cloudfunctions/node_modules/sharp');
const root = path.resolve(__dirname, '..');
const sources = path.join(root, 'design/home-promos/animations');
const output = path.join(root, 'miniprogram/assets/home');
const promos = [
  { name: 'invite-cashback', key: 'invite', originalGifBytes: 164857 },
  { name: 'customer-gift', key: 'gift', originalGifBytes: 243880 },
];
async function build() {
  const css = ['/* Generated by scripts/build-promo-frames.cjs. */'];
  const manifest = [];
  for (const promo of promos) {
    const source = path.join(sources, `${promo.name}-source.webp`);
    const metadata = await sharp(source, { animated: true }).metadata();
    const width = metadata.width, height = metadata.pageHeight, columns = 7;
    const frames = metadata.pages, rows = Math.ceil(frames / columns);
    const overlays = await Promise.all(Array.from({ length: frames }, async (_, i) => ({
      input: await sharp(source, { page: i }).png().toBuffer(),
      left: (i % columns) * width, top: Math.floor(i / columns) * height,
    })));
    const raw = await sharp({ create: { width: columns * width, height: rows * height,
      channels: 4, background: '#ffffff' } }).composite(overlays).raw().toBuffer();
    const encode = quality => sharp(raw, { raw: {width:columns*width,height:rows*height,channels:4} })
      .jpeg({ quality, chromaSubsampling:'4:2:0', mozjpeg:true }).toBuffer();
    const candidates = new Map();
    async function candidate(quality) {
      if (!candidates.has(quality)) candidates.set(quality, await encode(quality));
      return candidates.get(quality);
    }
    let low=1, high=100;
    while(low<=high) {
      const quality=Math.floor((low+high)/2), image=await candidate(quality);
      if(image.length<=promo.originalGifBytes) low=quality+1; else high=quality-1;
    }
    for(const quality of [Math.max(1,high),Math.min(100,low)]) await candidate(quality);
    const [quality,image] = [...candidates].sort((a,b) =>
      Math.abs(a[1].length-promo.originalGifBytes)-Math.abs(b[1].length-promo.originalGifBytes))[0];
    if(Math.abs(image.length/promo.originalGifBytes-1)>0.05) throw Error(`${promo.name}: JPG exceeds size tolerance`);
    const file=`${promo.name}-frames-v261025.jpg`;
    fs.writeFileSync(path.join(output,file),image);
    await sharp(source,{page:0}).jpeg({quality,chromaSubsampling:'4:2:0',mozjpeg:true})
      .toFile(path.join(output,`${promo.name}-poster-v261025.jpg`));
    const duration=metadata.delay.reduce((a,b)=>a+b,0);
    css.push(`.promo-frame-sheet--${promo.key} { width: ${columns*100}%; height: ${rows*100}%; animation: ${promo.key}-promo-frames ${duration}ms steps(1, end) infinite; }`,
      `@keyframes ${promo.key}-promo-frames {`);
    let elapsed=0;
    for(let i=0;i<frames;i++) {
      css.push(`  ${(elapsed/duration*100).toFixed(6)}% { transform: translate(${(-(i%columns)/columns*100).toFixed(6)}%, ${(-Math.floor(i/columns)/rows*100).toFixed(6)}%); }`);
      elapsed+=metadata.delay[i];
    }
    css.push('  100% { transform: translate(0%, 0%); }','}');
    manifest.push({...promo,quality,bytes:image.length,file,width,height,columns,rows,frames,duration});
    console.log(`${promo.name}: JPG quality ${quality}, ${image.length} bytes; original GIF ${promo.originalGifBytes} bytes`);
  }
  fs.writeFileSync(path.join(root,'miniprogram/assets/components/static-image/promo-frames.wxss'),css.join('\n')+'\n');
  fs.writeFileSync(path.join(sources,'frame-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
}
build().catch(error=>{console.error(error);process.exitCode=1;});
