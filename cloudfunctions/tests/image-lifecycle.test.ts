// @ts-nocheck
const assert = require('assert');
const { makeRuntime, localAddress } = require('./regressions.test');
const { imageLifecycleRuntime, cleanup, cleanupQueue, compactDeletedStates, prepareUpload, replaceReference, matches, uses, files, stateId } = require('../shared/image-lifecycle');
const { shopEndpoint } = require('../shared/shop');
const { adminEndpoint } = require('../shared/admin');
const { toPublicError } = require('../shared/errors');
const old = 'cloud://test.bucket/admin/products/old.jpg';
const next = 'cloud://test.bucket/admin/products/new.webp';
async function run() {
  const serial = makeRuntime();
  const runSerialTransaction = serial.db.runTransaction.bind(serial.db);
  serial.db.runTransaction = worker => runSerialTransaction(tx => {
    let inFlight = false;
    return worker({ ...tx, collection(name) {
      const ref = tx.collection(name);
      return { ...ref, doc(id) {
        const doc = ref.doc(id);
        return { ...doc, async get() {
          assert.strictEqual(inFlight, false, 'CloudBase transactions reject overlapping document requests');
          inFlight = true;
          try { await new Promise(resolve => setImmediate(resolve)); return await doc.get(); }
          finally { inFlight = false; }
        } };
      } };
    } });
  });
  const imageIds = [next, 'cloud://test.bucket/home/banner-2.webp', 'cloud://test.bucket/home/banner-3.webp'];
  await imageLifecycleRuntime(serial).db.collection('homeContents').doc('home.page-config').set({
    slot: 'home.page-config', type: 'pageConfig', payload: { banners: imageIds.map(image => ({ image, productId: '' })) },
  });
  assert.deepStrictEqual(serial.records.homeContents['home.page-config'].payload.banners.map(item => item.image), imageIds);
  const covers = makeRuntime();
  const secondary = 'cloud://test.bucket/admin/products/secondary.webp';
  covers.records.products['product-1'].secondaryImage = secondary;
  covers.app = { deleteFile: async ({ fileList }) => ({ fileList: fileList.map(fileID => ({ fileID, code: 'SUCCESS' })) }) };
  assert.deepStrictEqual((await cleanup(covers, { fileList: [secondary] })).retained, [secondary], 'a secondary cover is protected even if only its dedicated field references it');
  const coverRuntime = imageLifecycleRuntime(covers);
  await coverRuntime.db.collection('products').doc('product-1').update({ secondaryImage: '' });
  assert(coverRuntime.removedImages.has(secondary), 'removing a secondary cover queues image cleanup');
  assert.deepStrictEqual((await cleanup(covers, { fileList: [secondary] })).deleted, [secondary]);
  const metadata = makeRuntime();
  metadata.records.products['product-1'].images = [next];
  metadata.records.homeContents = { 'home.page-config': { _id: 'home.page-config', payload: { banners: [{ productId: 'product-1', image: next }], sections: [{ productIds: ['product-1'] }] } } };
  const transaction = metadata.db.runTransaction;
  let transactions = 0;
  metadata.db.runTransaction = (fn) => { transactions++; return transaction(fn); };
  await adminEndpoint({}, { auth: { uid: 'admin' } }, metadata, 'products.update', { id: 'product-1', status: 'inactive' });
  assert.strictEqual(metadata.records.products['product-1'].status, 'inactive');
  assert.strictEqual(metadata.records.homeContents['home.page-config'].payload.banners[0].productId, '');
  assert.strictEqual(transactions, 1, 'downlisting uses only the business transaction');
  assert(!metadata.writes.some((write) => write.collection === 'settings'), 'unchanged image references do not contend on the cleanup fence');
  await imageLifecycleRuntime(metadata).db.collection('skus').doc('sku-new').update({ stockQuantity: 9 });
  assert.strictEqual(transactions, 1, 'stock-only updates do not start image transactions');
  assert.strictEqual(metadata.records.skus['sku-new'].stockQuantity, 9);
  assert.strictEqual(toPublicError(new Error('Transaction request failed')).code, 'INTERNAL_ERROR');
  assert.strictEqual(toPublicError(Object.assign(new Error('write conflict'), { code: 'DATABASE_TRANSACTION_CONFLICT' })).code, 'CONFLICT');
  const runtime = makeRuntime();
  const deleted = [];
  runtime.app = { deleteFile: async ({fileList}) => { deleted.push(...fileList); return {fileList:fileList.map(fileID=>({fileID,code:'SUCCESS'}))}; } };
  runtime.records.products['product-1'].images = [old];
  runtime.records.orders.history = {_id:'history',items:[{image:old}]};
  const wrapped = imageLifecycleRuntime(runtime);
  await wrapped.db.collection('products').doc('product-1').update({images:[next]});
  assert(wrapped.removedImages.has(old));
  assert.deepStrictEqual((await cleanup(runtime,{fileList:[old]})).retained,[old]);
  assert.strictEqual(deleted.length,0,'historical order protects shared original');
  runtime.records.payments = { draft: { _id: 'draft', status: 'pending', draftOrders: [{ items: [{ image: next }] }] } };
  assert.deepStrictEqual((await cleanup(runtime,{fileList:[next]})).retained,[next], 'unpaid payment snapshots protect images before any formal order exists');
  delete runtime.records.payments.draft;
  await replaceReference(runtime,{oldFileID:old,newFileID:next,source:'orders',id:'history'});
  assert.strictEqual(runtime.records.orders.history.items[0].image,next);
  await wrapped.db.collection('products').doc('product-1').update({images:[old]});
  assert.deepStrictEqual(runtime.records.products['product-1'].images,[next],'stale clients use migrated image');
  assert.deepStrictEqual((await cleanup(runtime,{fileList:[old]})).deleted,[old]);
  const unused = 'cloud://test.bucket/admin/products/unused.jpg';
  await cleanup(runtime,{fileList:[unused]});
  await assert.rejects(()=>wrapped.db.collection('products').doc('product-1').update({images:[unused]}),e=>e.code==='CONFLICT');
  const failure = makeRuntime();
  failure.app = {deleteFile:async()=>{throw new Error('must not delete');}};
  const originalCollection = failure.db.collection;
  failure.db.collection = name => name==='orders' ? {orderBy(){throw new Error('scan failed');}} : originalCollection(name);
  await assert.rejects(()=>cleanup(failure,{fileList:[old]}),/scan failed/);
  const race = makeRuntime();
  race.app = {deleteFile:async()=>{throw new Error('must not delete after concurrent write');}};
  const raceTransaction = race.db.runTransaction;
  race.db.runTransaction = fn => { race.records.settings = {'__image_cleanup_control':{version:10}}; return raceTransaction(fn); };
  await assert.rejects(()=>cleanup(race,{fileList:[old]}),e=>e.code==='CONFLICT');
  assert(matches('https://bucket.tcb.qcloud.la/admin/products/old.jpg?sign=a',old));
  assert(!matches('https://bucket.evil.com/admin/products/old.jpg',old));
  const leased = makeRuntime();
  const removedFiles = [];
  leased.app = {
    getUploadMetadata: async ({ cloudPath }) => ({ data: { fileId: `cloud://test.bucket/${cloudPath}` } }),
    deleteFile: async ({ fileList }) => { removedFiles.push(...fileList); return { fileList: fileList.map(fileID => ({ fileID, code: 'SUCCESS' })) }; },
  };
  const lease = await prepareUpload(leased, 'user/comments', 'user-1');
  assert(leased.records.settings[stateId(lease.fileID)].imageCleanupPending, 'reserve before bytes are uploaded');
  assert.deepStrictEqual((await cleanupQueue(leased, 'user-1')).deleted, [], 'active upload lease is protected');
  await assert.rejects(() => shopEndpoint({}, { auth: { uid: 'other-user' } }, leased, 'storage.cleanup', { fileList: [lease.fileID] }), error => error.code === 'FORBIDDEN');
  leased.records.settings[stateId(lease.fileID)].cleanupAfter = '2000-01-01T00:00:00.000Z';
  leased.app.deleteFile = async () => { throw new Error('storage unavailable'); };
  await assert.rejects(() => cleanupQueue(leased, 'user-1'), /storage unavailable/);
  assert(leased.records.settings[stateId(lease.fileID)].imageCleanupPending, 'failure persists without a browser response');
  leased.app.deleteFile = async ({ fileList }) => ({ fileList: fileList.map(fileID => ({ fileID, code: 'SUCCESS' })) });
  assert.deepStrictEqual((await cleanupQueue(leased, 'user-1')).deleted, [lease.fileID]);
  const kept = await prepareUpload(leased, 'user/comments', 'user-1');
  leased.records.comments.keep = { _id: 'keep', userId: 'user-1', images: [kept.fileID] };
  assert.deepStrictEqual((await cleanup(leased, { fileList: [kept.fileID] })).retained, [kept.fileID]);
  assert.strictEqual(leased.records.settings[stateId(kept.fileID)].imageCleanupPending, false);
  await imageLifecycleRuntime(leased).db.collection('comments').doc('keep').remove();
  assert(leased.records.settings[stateId(kept.fileID)].imageCleanupPending, 'business deletion queues files in the same transaction');
  assert.deepStrictEqual((await cleanupQueue(leased, 'user-1')).deleted, [kept.fileID]);
  const withdrawn = makeRuntime();
  const user = { auth: { uid: 'user-1' } };
  const order = await shopEndpoint({}, user, withdrawn, 'orders.create', { requestKey: 'withdraw-image', addressId: 'address-1', address: localAddress, items: [{ skuId: 'sku-new', quantity: 1 }] });
  const claim = await shopEndpoint({}, user, withdrawn, 'afterSales.create', { orderId: order._id, type: 20, reason: '取消', images: [old] });
  await shopEndpoint({}, user, withdrawn, 'afterSales.withdraw', { afterSaleId: claim._id });
  assert.strictEqual(withdrawn.records.afterSales[claim._id], undefined);
  assert.deepStrictEqual(withdrawn.records.orders[order._id].afterSaleIds, []);
  assert(withdrawn.records.settings[stateId(old)].imageCleanupPending, 'withdrawal persists image cleanup even if response is lost');
  const catalog = makeRuntime();
  catalog.records.skus['sku-new'].skuImage = next;
  await adminEndpoint({}, { auth: { uid: 'admin' } }, catalog, 'products.delete', { id: 'product-1' });
  assert.strictEqual(catalog.records.skus['sku-new'], undefined);
  assert(catalog.records.settings[stateId(next)].imageCleanupPending, 'deleted product retires its SKU images too');
  const id = 'cloud://cloud1-test.636c-cloud1-test-123/admin/products/embedded.webp';
  const html = '<img src="https://636c-cloud1-test-123.tcb.qcloud.la/admin/products/embedded.webp?sign=abc">';
  assert(files(html).includes(id));
  assert(uses(html, id), 'embedded URLs must be protected by the same parser that discovers them');
  const terminal = makeRuntime();
  terminal.app = runtime.app;
  terminal.records.payments = { expired: { _id: 'expired', status: 'closed', draftOrders: [{ items: [{ image: old }] }] } };
  assert.deepStrictEqual((await cleanup(terminal, { fileList: [old] })).deleted, [old], 'closed unpaid drafts no longer pin images');
  terminal.records.payments.expired.status = 'paid';
  terminal.records.payments.expired.draftOrders[0].items[0].image = next;
  assert.deepStrictEqual((await cleanup(terminal, { fileList: [next] })).deleted, [next], 'paid drafts do not pin an image after formal orders are deleted');
  const readOnly = makeRuntime();
  readOnly.records.homeContents = { 'home.page-config': { _id: 'home.page-config', payload: { banners: [{ image: old, productId: 'missing' }] } } };
  const before = JSON.stringify(readOnly.records);
  const home = await adminEndpoint({}, {}, readOnly, 'home.get', { id: 'home.page-config' });
  assert.strictEqual(home.payload.banners[0].productId, '');
  assert.strictEqual(JSON.stringify(readOnly.records), before, 'home.get must not write, create collections, or start a transaction');
  const aliases = makeRuntime();
  aliases.records.settings = { [stateId(old)]: { _id: stateId(old), fileID: old, status: 'deleted', newFileID: next }, [stateId(next)]: { _id: stateId(next), fileID: next, imageCleanupPending: false } };
  await compactDeletedStates(aliases);
  assert.strictEqual(aliases.records.settings[stateId(old)].newFileID, next, 'a live migration alias is preserved');
  aliases.records.settings[stateId(next)].status = 'deleted';
  await compactDeletedStates(aliases);
  await compactDeletedStates(aliases);
  assert.deepStrictEqual(aliases.records.settings[stateId(old)], { _id: stateId(old), status: 'deleted', imageCleanupPending: false });
  console.log('PASS image cleanup preserves history, fails closed, fences writes and migrates stale references');
  console.log('PASS upload leases, durable cleanup retry, owner guards, withdrawal and deleted-product SKU cleanup');
}
module.exports = {run};
